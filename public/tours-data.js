// Поиск тура по id (или по названию, если id не передан)
function findTour(param) {
  if (!param) return null;
  const key = String(param).trim().toLowerCase();
  let decoded = key;
  try {
    decoded = decodeURIComponent(key);
  } catch (e) {
    // если строка уже декодирована — используем как есть
  }

  const allTours = TOURS.concat(CATALOG_TOURS);

  return allTours.find(t => t.id === key)
    || allTours.find(t => t.id === decoded)
    || allTours.find(t => t.title.toLowerCase() === key)
    || allTours.find(t => t.title.toLowerCase() === decoded);
}
